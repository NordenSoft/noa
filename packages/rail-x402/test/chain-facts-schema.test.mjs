test("schema mirror: transfer — every member, plus the not-an-object refusal (R-19(b) uniqueness at the record boundary)", () => {
  const transferSchema = schema.properties.transfer.oneOf.find((b) => b.type === "object");
  for (const k of transferSchema.required) {
    const v = clone();
    delete v.transfer[k];
    assert.equal(validateChainFacts(v).ok, false, `transfer schema requires "${k}"`);
  }
  const extra = clone();
  extra.transfer.smuggled = 1;
  assert.equal(validateChainFacts(extra).ok, false, "transfer schema refuses unknown members");
  for (const [k, node] of Object.entries(transferSchema.properties)) {
    const v = clone();
    v.transfer[k] = violationFor(node);
    assert.equal(validateChainFacts(v).ok, false, `transfer schema constrains "${k}"`);
  }
  // The oneOf admits null | ONE object. An array of transfers matches neither branch — and that IS
  // the uniqueness rule at the record boundary: a caller with two qualifying logs cannot produce a
  // conforming record, and presenting both is refused, never reduced to a pick.
  const twoTransfers = clone();
  twoTransfers.transfer = [clone().transfer, clone().transfer];
  assert.equal(validateChainFacts(twoTransfers).ok, false, "an array of transfers must be refused, never picked from");
});

test("uppercase hex is refused everywhere the schema pins lowercase (EIP-55 casing is presentation, not identity)", () => {
  for (const mutate of [
    (v) => { v.asset = v.asset.toUpperCase(); },
    (v) => { v.network = "EIP155:8453"; },
    (v) => { v.authorizationUsedLogs[0].txHash = v.authorizationUsedLogs[0].txHash.toUpperCase(); },
    (v) => { v.transfer.address = v.transfer.address.toUpperCase(); },
    (v) => { v.transfer.from = v.transfer.from.toUpperCase(); },
    (v) => { v.transfer.to = v.transfer.to.toUpperCase(); },
  ]) {
    const v = clone();
    mutate(v);
    assert.equal(validateChainFacts(v).ok, false, "uppercase variant accepted");
  }
});
