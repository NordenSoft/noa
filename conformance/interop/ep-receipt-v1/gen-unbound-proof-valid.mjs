#!/usr/bin/env node
/**
 * Generator + PROOF for the EP-RECEIPT-v1 isolating vector
 * `reject_v2_unbound_leaf_proof_valid`.
 *
 * WHY THIS VECTOR EXISTS
 * ----------------------
 * draft-hillier-scitt-arp proposes a divergence axis `anchor-leaf-not-bound-to-payload`,
 * distinct from `log-proof-broken`. The distinction is real — a valid inclusion proof for a
 * leaf nobody tied to this payload is a genuine proof of a proposition nobody asked about, and
 * it survives a log audit, which is exactly why it needs its own name. But the EMILIA
 * `frozen-v1` corpus contains no vector that ISOLATES it: the two anchor-negative vectors it
 * publishes each fail BOTH checks at once, so neither can distinguish the two failure modes.
 * That is measured, not asserted — run this file and read the CONTROLS table.
 *
 * This vector isolates it: the receipt signature verifies, the inclusion proof reconstructs the
 * declared root EXACTLY, and the only thing wrong is that the proven leaf is not this receipt's
 * payload. A verifier that reports `log-proof-broken` here is wrong; a verifier that reports
 * "valid" here is worse.
 *
 * CONSTRUCTION (EP-MERKLE-v2, confirmed against EMILIA's own published accept vector below)
 *   leaf   = SHA-256( 0x00 || JCS(payload) )
 *   branch = SHA-256( 0x01 || leftHex || rightHex )      -- positional, hex-string operands
 *   signature = Ed25519 over JCS(payload), base64url unpadded
 *
 * The construction is not taken on trust: `proveConstruction()` recomputes the leaf AND the root
 * of EMILIA's published `accept_with_merkle_anchor_v2` and requires byte equality with the
 * published values before this generator will emit anything.
 *
 * KEY MATERIAL: deterministic from a fixed, published test-only seed, so anyone can regenerate
 * this vector byte-for-byte. It is a CONFORMANCE key. It signs nothing else and guards nothing.
 *
 * PROVENANCE: this vector is authored in the EP-RECEIPT-v1 shape because that is the corpus the
 * axis belongs to. It is NOT a `noa.receipt/0.1` vector: the NOA profile has no inclusion-proof
 * or anchor structure at all, so the failure this vector isolates is not expressible in it. It
 * lives under conformance/interop/ rather than conformance/vectors/ for that reason, and because
 * conformance/vectors/ is machine-generated by scripts/gen-vectors.ts on every `npm test`.
 *
 * Usage:  node gen-unbound-proof-valid.mjs          # prove + print, write nothing
 *         node gen-unbound-proof-valid.mjs --write  # prove + write the vector file
 *
 * @license Apache-2.0
 */
import { createHash, createPrivateKey, sign as edSign, createPublicKey, verify as edVerify } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'unbound-proof-valid.vector.json');

// ── EP-MERKLE-v2 primitives ──────────────────────────────────────────────────────────────────
const sha256hex = (buf) => createHash('sha256').update(buf).digest('hex');

/** JCS-style canonical JSON: recursive key-sorted, no whitespace. */
function jcs(v) {
  if (v === null || typeof v !== 'object') return JSON.stringify(v);
  if (Array.isArray(v)) return '[' + v.map(jcs).join(',') + ']';
  return '{' + Object.keys(v).sort().map((k) => JSON.stringify(k) + ':' + jcs(v[k])).join(',') + '}';
}
const leafHash = (payload) => sha256hex(Buffer.concat([Buffer.from([0x00]), Buffer.from(jcs(payload), 'utf8')]));
const branch = (l, r) => sha256hex(Buffer.concat([Buffer.from([0x01]), Buffer.from(l, 'utf8'), Buffer.from(r, 'utf8')]));

/** Walk an inclusion proof from a leaf to a root. `position` is the side the SIBLING sits on. */
function walkProof(leaf, proof) {
  let h = leaf;
  for (const step of proof) h = step.position === 'right' ? branch(h, step.hash) : branch(step.hash, h);
  return h;
}

const b64u = (buf) => buf.toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const unb64u = (s) => Buffer.from(s.replace(/-/g, '+').replace(/_/g, '/'), 'base64');

// ── Ground truth: EMILIA frozen-v1 receipts.v1.json, if reachable ─────────────────────────────
// Published values from emiliaprotocol/emilia-protocol @ 125e4f4311f1319fef3f6d55c935c9ea4da5fc1b,
// conformance/clean-room/frozen-v1/conformance/vectors/receipts.v1.json. Inlined so this file
// proves itself with no clone present; verified against the clone when EMILIA_RECEIPTS is set.
const PUBLISHED = {
  accept_with_merkle_anchor_v2: {
    payload: { receipt_id: 'tr_anchored_v2', issuer: 'ep:demo' },
    leaf_hash: '49e4fa6eec990de1897dfcdd3b7a7cb6af458bf8d8a2aaddb9c61837bb26f804',
    merkle_proof: [{ hash: '52ab2e6d1cf6ebb89e4d01bb94ca71b5df78f609154b2735251abbeb37274038', position: 'right' }],
    merkle_root: '388fbc92013502492595c9092b268c1ec0ab562ae2bec40602e83a9cca0239c3',
  },
  reject_v2_unbound_leaf: {
    payload: { receipt_id: 'tr_v2_unbound', issuer: 'ep:demo' },
    leaf_hash: '407f447a518bd5dd58e4c17b09934eb0e5041816b9cebf85d2a44b70d3fba0ab',
    merkle_proof: [{ hash: '52ab2e6d1cf6ebb89e4d01bb94ca71b5df78f609154b2735251abbeb37274038', position: 'right' }],
    merkle_root: '388fbc92013502492595c9092b268c1ec0ab562ae2bec40602e83a9cca0239c3',
  },
  reject_tampered_anchor: {
    payload: { receipt_id: 'tr_badanchor', issuer: 'ep:demo' },
    leaf_hash: 'c0cb6810219b31e0542dedc589b9dcba8bd9eca0aa0ce95c1555183256c67c2b',
    merkle_proof: [{ hash: '521536a74c32eeea57beaec93f3634392f3099ea864bf0892d442a447bc17795', position: 'right' }],
    merkle_root: '73027e0c013ed6ce34519954ad6250cd62badd5bc5e23e2bcf46b5c92451af62',
  },
};

/** Refuse to emit anything unless our construction reproduces EMILIA's published accept vector. */
function proveConstruction() {
  const a = PUBLISHED.accept_with_merkle_anchor_v2;
  const leaf = leafHash(a.payload);
  const root = walkProof(a.leaf_hash, a.merkle_proof);
  const leafOk = leaf === a.leaf_hash;
  const rootOk = root === a.merkle_root;
  console.log('CONSTRUCTION CHECK against EMILIA published accept_with_merkle_anchor_v2');
  console.log(`  leaf recomputed : ${leaf}`);
  console.log(`  leaf published  : ${a.leaf_hash}   ${leafOk ? 'MATCH' : 'MISMATCH'}`);
  console.log(`  root recomputed : ${root}`);
  console.log(`  root published  : ${a.merkle_root}   ${rootOk ? 'MATCH' : 'MISMATCH'}`);
  if (!leafOk || !rootOk) {
    throw new Error('EP-MERKLE-v2 construction does not reproduce the published accept vector; refusing to emit.');
  }
  console.log('  => construction confirmed; safe to mint a vector under it\n');
}

/** Show that neither published anchor-negative vector isolates the two failure modes. */
function controls() {
  const rows = [];
  for (const [id, v] of Object.entries(PUBLISHED)) {
    rows.push({
      id,
      bound: leafHash(v.payload) === v.leaf_hash,
      proofValid: walkProof(v.leaf_hash, v.merkle_proof) === v.merkle_root,
    });
  }
  console.log('CONTROLS — published EP-RECEIPT-v1 anchor vectors');
  console.log('  vector                              leaf-bound?  proof-valid?  isolates?');
  for (const r of rows) {
    const isolating = !r.bound && r.proofValid;
    console.log(
      `  ${r.id.padEnd(35)} ${String(r.bound).padEnd(12)} ${String(r.proofValid).padEnd(13)} ${isolating ? 'YES' : 'no'}`,
    );
  }
  console.log('  Both negatives fail BOTH checks, so neither separates');
  console.log('  anchor-leaf-not-bound-to-payload from log-proof-broken.\n');
  return rows;
}

// ── Mint the isolating vector ────────────────────────────────────────────────────────────────
/**
 * Deterministic test-only key. The seed is published here on purpose: the vector must be
 * regenerable byte-for-byte by anyone who wants to contradict it.
 */
const SEED_HEX = '6e6f612d6172702d696e7465726f702d766563746f722d763120746573746b31'; // 32 bytes, ASCII "noa-arp-interop-vector-v1 testk1"
function deterministicKey() {
  // Ed25519 PKCS8 = fixed 16-byte header || 32-byte seed.
  const pkcs8 = Buffer.concat([
    Buffer.from('302e020100300506032b657004220420', 'hex'),
    Buffer.from(SEED_HEX, 'hex'),
  ]);
  return createPrivateKey({ key: pkcs8, format: 'der', type: 'pkcs8' });
}

function build() {
  const priv = deterministicKey();
  const pub = createPublicKey(priv);
  const spki = pub.export({ type: 'spki', format: 'der' });

  // This receipt's OWN payload. Its leaf is NOT what the anchor proves.
  const payload = { receipt_id: 'tr_v2_unbound_proof_valid', issuer: 'ep:demo' };

  // The anchor proves a DIFFERENT, real leaf: the one belonging to EMILIA's published
  // accept_with_merkle_anchor_v2 receipt, under EMILIA's published root, with EMILIA's published
  // sibling. Every anchor field is a real value from a real tree — the proof is genuine. It is
  // simply a proof about someone else's payload.
  const borrowed = PUBLISHED.accept_with_merkle_anchor_v2;

  const signature = b64u(edSign(null, Buffer.from(jcs(payload), 'utf8'), priv));

  return {
    id: 'reject_v2_unbound_leaf_proof_valid',
    description:
      'v2 anchor whose inclusion proof reconstructs the declared root EXACTLY, but whose leaf is not this receipt payload. Signature valid, proof valid, binding absent — isolates anchor-leaf-not-bound-to-payload from log-proof-broken.',
    expect: { valid: false },
    reason: 'anchor_leaf_unbound',
    contributed_by: 'NordenSoft/noa (noa-receipt) — contributed to the EP-RECEIPT-v1 corpus',
    isolates: {
      axis: 'anchor-leaf-not-bound-to-payload',
      distinct_from: 'log-proof-broken',
      leaf_bound_to_payload: false,
      inclusion_proof_reconstructs_root: true,
      note: 'The borrowed leaf/sibling/root are the published values of accept_with_merkle_anchor_v2, so the proof is a genuine proof about a genuine leaf in a genuine tree — just not this receipt payload.',
    },
    public_key: b64u(spki),
    document: {
      '@version': 'EP-RECEIPT-v1',
      payload,
      signature: { algorithm: 'Ed25519', value: signature },
      anchor: {
        alg: 'EP-MERKLE-v2',
        leaf_hash: borrowed.leaf_hash,
        merkle_proof: borrowed.merkle_proof,
        merkle_root: borrowed.merkle_root,
      },
    },
  };
}

/** Independently re-verify the emitted vector's three claims. */
function proveVector(v) {
  const doc = v.document;
  const sigOk = edVerify(
    null,
    Buffer.from(jcs(doc.payload), 'utf8'),
    createPublicKey({ key: unb64u(v.public_key), format: 'der', type: 'spki' }),
    unb64u(doc.signature.value),
  );
  const ownLeaf = leafHash(doc.payload);
  const bound = ownLeaf === doc.anchor.leaf_hash;
  const reconstructed = walkProof(doc.anchor.leaf_hash, doc.anchor.merkle_proof);
  const proofValid = reconstructed === doc.anchor.merkle_root;

  console.log('MINTED VECTOR — reject_v2_unbound_leaf_proof_valid');
  console.log(`  payload JCS               : ${jcs(doc.payload)}`);
  console.log(`  signature verifies        : ${sigOk}            <- must be true`);
  console.log(`  leaf(this payload)        : ${ownLeaf}`);
  console.log(`  anchor.leaf_hash          : ${doc.anchor.leaf_hash}`);
  console.log(`  leaf bound to payload     : ${bound}           <- must be FALSE (the defect)`);
  console.log(`  proof reconstructs        : ${reconstructed}`);
  console.log(`  anchor.merkle_root        : ${doc.anchor.merkle_root}`);
  console.log(`  inclusion proof valid     : ${proofValid}            <- must be TRUE (isolation)`);

  const ok = sigOk && !bound && proofValid;
  console.log(`\n  ISOLATION ${ok ? 'DEMONSTRATED' : 'FAILED'}: signature valid + proof valid + leaf unbound`);
  if (!ok) throw new Error('minted vector does not demonstrate the isolation it claims');
  return ok;
}

// ── main ─────────────────────────────────────────────────────────────────────────────────────
proveConstruction();
controls();
const vector = build();
proveVector(vector);

if (process.argv.includes('--write')) {
  writeFileSync(OUT, JSON.stringify(vector, null, 2) + '\n');
  console.log(`\nwrote ${OUT}`);
} else {
  console.log('\n(dry run — pass --write to emit the vector file)');
}
